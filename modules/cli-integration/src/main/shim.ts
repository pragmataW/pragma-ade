import { writeFileAtomic } from '@pragma/sdk/main'
import { POSIX_EXEC_MODE, WIN32 } from '../constants'
import type { CliPaths } from './paths'

type ShimPaths = Pick<CliPaths, 'execPath' | 'bundlePath' | 'bridgeFile'>

const SINGLE_QUOTE_RE = /'/g
const PERCENT_RE = /%/g
const ESCAPED_PERCENT = '%%'
/** POSIX single quoting: `'` → `'\''`. */
const sq = (s: string): string => `'${s.replace(SINGLE_QUOTE_RE, "'\\''")}'`
/** cmd.exe: `%` → `%%` inside double quotes (paths cannot contain `"`). */
const dq = (s: string): string => `"${s.replace(PERCENT_RE, ESCAPED_PERCENT)}"`
const HEADER = '# Generated by Pragma ADE. Regenerated on every app start; do not edit.'

export function renderPosixShim(p: ShimPaths): string {
  return [
    '#!/bin/sh',
    HEADER,
    `if [ -z "\${PRAGMA_BRIDGE_FILE:-}" ]; then PRAGMA_BRIDGE_FILE=${sq(p.bridgeFile)}; fi`,
    'export PRAGMA_BRIDGE_FILE',
    `ELECTRON_RUN_AS_NODE=1 exec ${sq(p.execPath)} ${sq(p.bundlePath)} "$@"`,
    '',
  ].join('\n')
}

export function renderCmdShim(p: ShimPaths): string {
  const bridgeFile = p.bridgeFile.replace(PERCENT_RE, ESCAPED_PERCENT)
  return [
    '@echo off',
    'setlocal',
    `if not defined PRAGMA_BRIDGE_FILE set "PRAGMA_BRIDGE_FILE=${bridgeFile}"`,
    'set ELECTRON_RUN_AS_NODE=1',
    `${dq(p.execPath)} ${dq(p.bundlePath)} %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].join('\r\n')
}

/** (Re)writes the platform's shim at `shimPath` atomically; same input → same file. */
export async function writeShims(p: CliPaths, platform: NodeJS.Platform): Promise<void> {
  if (platform === WIN32) return writeFileAtomic(p.shimPath, renderCmdShim(p))
  writeFileAtomic(p.shimPath, renderPosixShim(p), { mode: POSIX_EXEC_MODE })
}
