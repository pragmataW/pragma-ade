import { execFileSync } from 'node:child_process'
import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import type { CliPaths } from '../src/main/paths'
import { renderCmdShim, renderPosixShim, writeShims } from '../src/main/shim'

const POSIX = process.platform !== 'win32'
const dirs: string[] = []
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true })
})

const simple = { execPath: '/app/Electron', bundlePath: '/res/pragma.cjs', bridgeFile: '/ud/bridge.json' }

/** Paths under a temp dir named `a b'c`, with a fake Electron that echoes what the shim passed. */
function quotedPaths(): CliPaths {
  const root = join(mkdtempSync(join(tmpdir(), 'pragma-shim-')), "a b'c")
  dirs.push(root)
  mkdirSync(root, { recursive: true })
  const execPath = join(root, 'fake electron')
  writeFileSync(execPath, '#!/bin/sh\nprintf \'%s|%s|%s\' "$ELECTRON_RUN_AS_NODE" "$PRAGMA_BRIDGE_FILE" "$*"\n')
  chmodSync(execPath, 0o755)
  const binDir = join(root, 'bin')
  return {
    execPath,
    bundlePath: join(root, 'pragma.cjs'),
    bridgeFile: join(root, "it's bridge.json"),
    skillsDir: join(root, 'skills'),
    binDir,
    shimPath: join(binDir, 'pragma'),
  }
}

describe('shims', () => {
  it('posix shim quotes paths', () => {
    expect(renderPosixShim({ ...simple, execPath: "/o'k/Electron" })).toBe(
      [
        '#!/bin/sh',
        '# Generated by Pragma ADE. Regenerated on every app start; do not edit.',
        // biome-ignore lint/suspicious/noTemplateCurlyInString: shell parameter expansion, not a template
        'if [ -z "${PRAGMA_BRIDGE_FILE:-}" ]; then PRAGMA_BRIDGE_FILE=\'/ud/bridge.json\'; fi',
        'export PRAGMA_BRIDGE_FILE',
        "ELECTRON_RUN_AS_NODE=1 exec '/o'\\''k/Electron' '/res/pragma.cjs' \"$@\"",
        '',
      ].join('\n'),
    )
  })

  it('cmd shim content', () => {
    expect(renderCmdShim({ ...simple, bundlePath: 'C:\\100%\\pragma.cjs' })).toBe(
      [
        '@echo off',
        'setlocal',
        'if not defined PRAGMA_BRIDGE_FILE set "PRAGMA_BRIDGE_FILE=/ud/bridge.json"',
        'set ELECTRON_RUN_AS_NODE=1',
        '"/app/Electron" "C:\\100%%\\pragma.cjs" %*',
        'exit /b %ERRORLEVEL%',
        '',
      ].join('\r\n'),
    )
  })

  it.skipIf(!POSIX)('survives spaces and single quotes', async () => {
    const p = quotedPaths()
    await writeShims(p, process.platform)
    const out = execFileSync(p.shimPath, ['x', 'y z'], { env: { PATH: '/usr/bin:/bin' }, encoding: 'utf8' })
    expect(out).toBe(`1|${p.bridgeFile}|${p.bundlePath} x y z`)
  })

  it.skipIf(!POSIX)('an existing PRAGMA_BRIDGE_FILE is kept', async () => {
    const p = quotedPaths()
    await writeShims(p, process.platform)
    const env = { PATH: '/usr/bin:/bin', PRAGMA_BRIDGE_FILE: '/other.json' }
    expect(execFileSync(p.shimPath, [], { env, encoding: 'utf8' })).toBe(`1|/other.json|${p.bundlePath}`)
  })

  it.skipIf(!POSIX)('writeShims is idempotent and sets mode 0755', async () => {
    const p = quotedPaths()
    await writeShims(p, process.platform)
    const first = readFileSync(p.shimPath, 'utf8')
    await writeShims(p, process.platform)
    expect(readFileSync(p.shimPath, 'utf8')).toBe(first)
    expect(statSync(p.shimPath).mode & 0o777).toBe(0o755)
  })

  it('win32 writes pragma.cmd', async () => {
    const p = quotedPaths()
    await writeShims({ ...p, shimPath: join(p.binDir, 'pragma.cmd') }, 'win32')
    expect(readFileSync(join(p.binDir, 'pragma.cmd'), 'utf8')).toContain('@echo off')
  })
})
